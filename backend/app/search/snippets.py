"""
Snippet types — data structures for search result snippets.

Phase 9 introduces snippets: short, highlighted excerpts that show
users the most relevant part of a matching document.

Types defined here are used by the snippet generator and the search
service but do NOT depend on FastAPI, SQLAlchemy, or the index.
"""

from __future__ import annotations

from dataclasses import dataclass, field


@dataclass(frozen=True)
class SnippetPart:
    """A single segment of a snippet — either plain text or a highlight."""

    text: str
    highlight: bool = False


@dataclass(frozen=True)
class Snippet:
    """
    A search-result snippet with structured highlighting.

    Attributes
    ----------
    parts : list[SnippetPart]
        Ordered segments of text, each flagged as highlighted or not.
    field : str
        Which document field produced the snippet (``"title"`` or ``"body"``).
    matched_terms : list[str]
        Normalised query terms that were actually found in the snippet.
    """

    parts: list[SnippetPart]
    field: str
    matched_terms: list[str] = field(default_factory=list)

    @property
    def plain_text(self) -> str:
        """Concatenate all parts into unhighlighted text."""
        return "".join(p.text for p in self.parts)

    def to_html(self) -> str:
        """
        Render as HTML with ``<mark>`` highlighting.

        All text is HTML-escaped first, then highlighted terms are
        wrapped in ``<mark>`` tags.  This is safe for rendering
        with ``dangerouslySetInnerHTML`` because the content is
        entirely generated by this trusted internal routine.
        """
        import html as _html

        segments: list[str] = []
        for part in self.parts:
            escaped = _html.escape(part.text, quote=True)
            if part.highlight:
                segments.append(f"<mark>{escaped}</mark>")
            else:
                segments.append(escaped)
        return "".join(segments)

    def to_dict(self) -> dict:
        """Serialise for the API response."""
        return {
            "snippet_html": self.to_html(),
            "snippet_parts": [
                {"text": p.text, "highlight": p.highlight}
                for p in self.parts
            ],
        }
